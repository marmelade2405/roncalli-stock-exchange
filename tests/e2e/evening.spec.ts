import { test, expect, signIn } from './fixtures.js';
test('evening_flow_preserves_previews_and_resets_timer', async ({ page, context, testApp }) => {
  await signIn(page, testApp);
  await page.getByTestId('normal-bier-input').fill('2,50'); await page.getByTestId('normal-bier-input').blur();
  await expect(page.getByTestId('normal-bier-effective')).toContainText('2,50');
  await page.getByTestId('crash-bier-input').fill('1,40'); await page.getByTestId('crash-bier-input').blur();
  await expect(page.getByTestId('crash-bier-effective')).toContainText('1,40');
  const first = await context.newPage(); await testApp.attachPage(first); let blocked = false;
  await first.routeWebSocket('**/ws/public', socket => { const server = socket.connectToServer(); server.onMessage(message => { if (!blocked) socket.send(message); }); });
  const second = await context.newPage(); await testApp.attachPage(second);
  await Promise.all([first.goto('/display'), second.goto('/display')]);
  await expect(first.getByTestId('display-price-bier')).toContainText('2,00');
  await page.getByRole('button', { name: 'Markt starten', exact: true }).click();
  await testApp.advanceTo(60_000); await page.getByRole('button', { name: 'Börsencrash auslösen', exact: true }).click();
  await testApp.advanceTo(70_000);
  await expect(first.getByTestId('display-price-bier')).toContainText('1,40'); await expect(second.getByTestId('display-price-bier')).toContainText('1,40');
  await expect(page.getByTestId('crash-bier-input')).toHaveValue(''); await expect(page.getByTestId('normal-bier-input')).toHaveValue('2,50');
  await page.reload(); await expect(page.getByTestId('normal-bier-input')).toHaveValue('2,50');
  await testApp.restart();
  await expect(second.getByTestId('display-price-bier')).toContainText('1,40');
  await expect(page.getByTestId('normal-bier-input')).toHaveValue('2,50');
  blocked = true; await testApp.advanceTo(360_000);
  await expect(first.locator('[data-price]:visible')).toHaveCount(0); await expect(second.locator('[data-price]:visible')).toHaveCount(0);
  await testApp.advanceTo(370_000);
  await expect(first.getByTestId('display-waiting')).toBeVisible();
  await expect(second.getByTestId('display-price-bier')).toContainText('1,50');
  await expect(page.getByTestId('normal-bier-input')).toHaveValue('2,50');
  await expect(second.getByTestId('display-countdown')).toHaveText('20:00');
  blocked = false; await first.reload(); await expect(first.getByTestId('display-price-bier')).toContainText('1,50');
  await page.getByRole('button', { name: 'Laufliste', exact: true }).click();
  await expect(first.getByTestId('display-ticker')).toBeVisible(); await expect(second.getByTestId('display-ticker')).toBeVisible();
  await testApp.advanceTo(1_570_000);
  await expect(page.getByTestId('normal-bier-input')).toHaveValue('');
  await page.getByRole('button', { name: 'Übersicht', exact: true }).click();
  await expect(first.getByTestId('display-price-bier')).toContainText('2,50'); await expect(second.getByTestId('display-price-bier')).toContainText('2,50');
  await expect(second.getByTestId('display-change-bier')).toContainText('66,7');
});
